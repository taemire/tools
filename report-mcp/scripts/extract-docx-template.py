#!/usr/bin/env python3
"""Derive the DOCX template parts of the arx-pentest-report-1 renderer.

Reads the user's original Word report (ARX-PT-2026-051, 13 pages) and writes
the formatting parts that the DOCX renderer reuses to
pentestreport/assets/docx/. Only formatting is copied: styles, list
numbering, document settings, theme and font table. The body, header, footer,
notes, web settings and document properties carry report content or editing
history and are not copied; the renderer writes them from the request.

Usage:
    python3 -I scripts/extract-docx-template.py <original.docx> [<assets/docx dir>]

The output is deterministic for the same input file. Re-run it only when the
original form changes, then review the diff and the template hash.
"""

import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

PARTS = {
    "styles.xml": "word/styles.xml",
    "numbering.xml": "word/numbering.xml",
    "settings.xml": "word/settings.xml",
    "theme1.xml": "word/theme/theme1.xml",
    "fontTable.xml": "word/fontTable.xml",
}

NOT_COPIED = [
    "word/document.xml (report body)",
    "word/header1.xml (sample watermark text)",
    "word/footer1.xml (sample title text)",
    "word/footnotes.xml, word/endnotes.xml (separators only, not used)",
    "word/webSettings.xml (web publishing settings)",
    "docProps/core.xml, docProps/app.xml (author, last editor, dates, statistics)",
]


def sha256(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def strip_styles(x: str) -> tuple[str, list[str]]:
    y = re.sub(r"<w:rsid w:val=\"[0-9A-F]+\"/>", "", x)
    return y, ["remove w:rsid editing-session marks"]


def strip_settings(x: str) -> tuple[str, list[str]]:
    rules = [
        (r"<w:proofState [^>]*/>", "remove proofing state"),
        (r"<w:footnotePr>.*?</w:footnotePr>", "remove footnote separators (no notes part)"),
        (r"<w:endnotePr>.*?</w:endnotePr>", "remove endnote separators (no notes part)"),
        (r"<w:rsids>.*?</w:rsids>", "remove editing-session ids"),
        (r"<w14:docId [^>]*/>", "remove document id"),
        (r"<w15:docId [^>]*/>", "remove document id"),
        (r"<w:attachedTemplate [^>]*/>", "remove attached template"),
    ]
    done = []
    for pat, why in rules:
        y = re.sub(pat, "", x, flags=re.S)
        if y != x:
            done.append(why)
        x = y
    if "embedTrueTypeFonts" in x or "saveSubsetFonts" in x:
        raise SystemExit("settings.xml asks Word to embed fonts; the DOCX must not embed fonts")
    return x, done


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "pentestreport/assets/docx"
    data = src.read_bytes()
    out.mkdir(parents=True, exist_ok=True)
    record = {
        "$comment": "Formatting parts of the user's original Word report reused by the arx-pentest-report-1 DOCX renderer. Generated by scripts/extract-docx-template.py; do not edit by hand.",
        "form": "ARX-PT-2026-051 penetration-test report, Word 13 pages (user original, 2026-11-03)",
        "source_docx_sha256": sha256(data),
        "parts": {},
        "not_copied": NOT_COPIED,
        "fonts": {
            "declared": ["맑은 고딕", "Consolas", "Times New Roman"],
            "embedded": False,
            "note": "Font names only. Word on the reader's PC supplies the glyphs.",
        },
    }
    with zipfile.ZipFile(src) as z:
        for name, member in PARTS.items():
            raw = z.read(member)
            text = raw.decode("utf-8")
            transforms = []
            if name == "styles.xml":
                text, transforms = strip_styles(text)
            elif name == "settings.xml":
                text, transforms = strip_settings(text)
            for bad in ("w:embedRegular", "w:embedBold", "w:embedItalic", "w:embedBoldItalic"):
                if bad in text:
                    raise SystemExit(f"{member} references an embedded font ({bad})")
            b = text.encode("utf-8")
            (out / name).write_bytes(b)
            record["parts"][name] = {
                "from": member,
                "source_sha256": sha256(raw),
                "sha256": sha256(b),
                "transforms": transforms or ["copied unchanged"],
            }
    (out / "docx-template.json").write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({k: v["sha256"] for k, v in record["parts"].items()}, indent=2))


if __name__ == "__main__":
    main()
